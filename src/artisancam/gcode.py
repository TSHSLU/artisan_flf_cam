"""Cuts -> G-code text for the Snapmaker Artisan.

This module owns the machine dialect and the machine origin. The dialect is copied from a
program that ran successfully (Fusion 360 output): G21/G90, `M3 P<percent>`, only G0/G1
(arcs are already straight segments), X, Y and Z on every move, and the feed repeated on
every G1. Origin: top-left corner of the stock; stock frame y (downward) becomes machine
Y = -y. Z = 0 is the top of the stock; cutting is negative.
"""

from __future__ import annotations

from .config import Settings
from .toolpath import Cut

_TRANSLITERATE = str.maketrans({"ä": "ae", "ö": "oe", "ü": "ue", "Ä": "Ae", "Ö": "Oe", "Ü": "Ue", "ß": "ss"})


def _num(value: float) -> str:
    text = f"{value:.3f}"
    return "0.000" if text == "-0.000" else text


def _feed(value: float) -> str:
    return f"{value:.1f}".rstrip("0").rstrip(".")


def _comment_text(text: str) -> str:
    """G-code comments are plain ASCII on a single line."""
    text = text.translate(_TRANSLITERATE)
    return "".join(c if " " <= c <= "~" else "?" for c in text)


def generate_gcode(
    cuts: list[Cut], settings: Settings, label: str = "", slot_labels: list[str] | None = None
) -> str:
    """Return the program as text with LF line endings; use to_file_bytes() to write a file.

    `label` describes a single cover (";Text: ..." in the header). For a multi-cover run pass
    `slot_labels` instead, one "Slot n: ..." text per engraved slot; the header then also
    describes the fixture. The moves are written the same way in both cases.
    """
    if not cuts:
        raise ValueError("No cuts to write.")
    s = settings
    cut_z = -s.depth

    def move(code: str, point: tuple[float, float], z: float, feed: float | None = None) -> str:
        line = f"{code} X{_num(point[0])} Y{_num(-point[1])} Z{_num(z)}"
        return line if feed is None else f"{line} F{_feed(feed)}"

    lines = [
        ";Machine",
        ";vendor: Snapmaker",
        ";description: Generic Snapmaker Marlin v20180725",
        ";Generated by artisancam",
    ]
    if slot_labels is None:
        lines.append(f";Text: {_comment_text(label)}")
    else:
        lines += [f";{_comment_text(text)}" for text in slot_labels]
    lines.append(f";Stock {_num(s.stock_width)} x {_num(s.stock_length)} mm, origin top-left, Z0 = top of stock")
    if slot_labels is not None:
        lines.append(
            f";Fixture {s.columns} x {s.rows} slots, pitch {_num(s.pitch_x)} x {_num(s.pitch_y)} mm, "
            "origin = top-left corner of slot 1"
        )
    lines.append(f"M3 P{s.spindle_percent:g}")
    if s.spindle_warmup_s > 0:
        lines.append(f"G4 S{s.spindle_warmup_s:g}")
    lines += ["G21", "G90", ""]

    lines.append(move("G0", cuts[0].points[0], s.clearance_z))
    for cut in cuts:
        start, end = cut.points[0], cut.points[-1]
        lines.append(move("G0", start, s.retract_z))
        if s.feed_z < s.retract_z:
            lines.append(move("G0", start, s.feed_z))
        lines.append(move("G1", start, cut_z, s.plunge_feed))
        for point in cut.points[1:]:
            lines.append(move("G1", point, cut_z, s.cutting_feed))
        lines.append(move("G1", end, s.retract_z, s.retract_feed))
    lines += [move("G0", cuts[-1].points[-1], s.clearance_z), "G0 X0.000 Y0.000", "M5", ""]
    return "\n".join(lines)


def to_file_bytes(program: str) -> bytes:
    """ASCII with CRLF line endings, like the reference program."""
    return program.replace("\r\n", "\n").replace("\n", "\r\n").encode("ascii")
